const cursorDot = document.querySelector('.cursor-dot');
const cursorRing = document.querySelector('.cursor-ring');
const hasFinePointer = window.matchMedia('(hover: hover) and (pointer: fine)').matches;
const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)');

if (hasFinePointer && !prefersReducedMotion.matches && cursorDot && cursorRing) {
  document.body.classList.add('has-custom-cursor');
  let mouseX = -100;
  let mouseY = -100;
  let ringX = -100;
  let ringY = -100;
  let cursorVisible = false;

  const showCursor = () => {
    if (!cursorVisible) {
      cursorVisible = true;
      cursorDot.style.opacity = '1';
      cursorRing.style.opacity = '1';
    }
  };

  const hideCursor = () => {
    cursorVisible = false;
    cursorDot.style.opacity = '0';
    cursorRing.style.opacity = '0';
  };

  const updateCursorState = () => {
    const isFullscreen = !!(
      document.fullscreenElement ||
      document.webkitFullscreenElement ||
      document.mozFullScreenElement ||
      document.msFullscreenElement
    );
    const isModalOpen = document.body.classList.contains('modal-open');

    if (isFullscreen || isModalOpen) {
      document.body.classList.remove('has-custom-cursor');
      cursorDot.style.display = 'none';
      cursorRing.style.display = 'none';
      hideCursor();
    } else {
      document.body.classList.add('has-custom-cursor');
      cursorDot.style.display = 'block';
      cursorRing.style.display = 'block';
    }
  };

  document.addEventListener('fullscreenchange', updateCursorState);
  document.addEventListener('webkitfullscreenchange', updateCursorState);
  document.addEventListener('mozfullscreenchange', updateCursorState);
  document.addEventListener('MSFullscreenChange', updateCursorState);

  window.updateCursorState = updateCursorState;
  updateCursorState(); // initial state run

  document.addEventListener('pointermove', (e) => {
    mouseX = e.clientX;
    mouseY = e.clientY;
    
    // Prevent showing the custom cursor when modal or fullscreen is active
    const isFullscreen = !!(
      document.fullscreenElement ||
      document.webkitFullscreenElement
    );
    if (!isFullscreen && !document.body.classList.contains('modal-open')) {
      showCursor();
    }
  });

  document.addEventListener('pointerleave', hideCursor);
  const hoverTargets = document.querySelectorAll('.clip-card, .button, a, .lang-switch button, .modal-close, .modal-nav, .work-filters button, .journey-grid a');

  hoverTargets.forEach((target) => {
    target.addEventListener('pointerenter', () => cursorRing.classList.add('is-hover'));
    target.addEventListener('pointerleave', () => cursorRing.classList.remove('is-hover'));
  });

  const lerp = (a, b, t) => a + (b - a) * t;

  const updateCursorFrame = () => {
    ringX = lerp(ringX, mouseX, 0.12);
    ringY = lerp(ringY, mouseY, 0.12);

    cursorDot.style.transform = `translate(-50%, -50%) translate(${mouseX}px, ${mouseY}px)`;
    cursorRing.style.transform = `translate(-50%, -50%) translate(${ringX}px, ${ringY}px)`;

    requestAnimationFrame(updateCursorFrame);
  };
  requestAnimationFrame(updateCursorFrame);
}

