const heroTitle = document.querySelector('.hero-title');
if (heroTitle) {
  const titleLayers = heroTitle.querySelectorAll(':scope > span, :scope > em');
  let titleFrame = null;
  let titlePointerEvent = null;
  const updateTitleHoverPosition = (event) => {
    titlePointerEvent = event;
    if (titleFrame) return;

    titleFrame = requestAnimationFrame(() => {
      const pointer = titlePointerEvent;
      titleFrame = null;
      if (!pointer) return;

      titleLayers.forEach((layer) => {
        const layerRect = layer.getBoundingClientRect();
        layer.style.setProperty('--title-local-x', `${pointer.clientX - layerRect.left}px`);
        layer.style.setProperty('--title-local-y', `${pointer.clientY - layerRect.top}px`);
      });
    });
  };

  heroTitle.addEventListener('pointerenter', updateTitleHoverPosition);
  heroTitle.addEventListener('pointermove', updateTitleHoverPosition);
}

const splitHeroTitleIntoWords = () => {
  const heroTitleEl = document.querySelector('.hero-title');
  if (!heroTitleEl) return;

  const layers = heroTitleEl.querySelectorAll('.title-base, .title-accent');
  layers.forEach((layer) => {
    const text = layer.textContent.trim();
    const words = text.split(/\s+/);
    layer.innerHTML = words.map((word, i) =>
      `<span class="kinetic-word" data-word-index="${i}"><span class="kinetic-word-inner">${word}</span></span>${i < words.length - 1 ? ' ' : ''}`
    ).join('');
  });
};

