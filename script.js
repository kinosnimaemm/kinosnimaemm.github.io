const progressFill = document.querySelector('.scroll-progress span');
const hudIndex = document.querySelector('.hud-index');
const hudLabel = document.querySelector('.hud-label');
const sceneSections = [...document.querySelectorAll('.hero, .about-intro, .direction-panel, .cinema-interlude, .client-path, .contact')];
let ticking = false;

const clamp = (value, min = 0, max = 1) => Math.min(max, Math.max(min, value));
const getSceneLabel = (section) => {
  if (section.classList.contains('hero')) return 'opening frame';
  if (section.classList.contains('client-path')) return 'client path';
  if (section.classList.contains('contact')) return 'contact / booking';
  const heading = section.querySelector('h3, h2');
  return heading ? heading.textContent.trim() : 'portfolio scene';
};

const updateScrollMagic = () => {
  const scrollTop = lenis?.scroll || window.scrollY || document.documentElement.scrollTop;
  const maxScroll = Math.max(1, document.documentElement.scrollHeight - window.innerHeight);
  const pageProgress = clamp(scrollTop / maxScroll);
  document.documentElement.style.setProperty('--page-progress', pageProgress.toFixed(4));
  if (progressFill) progressFill.style.transform = `scaleX(${pageProgress})`;

  const scrollWordmark = document.querySelector('.scroll-wordmark');
  if (scrollWordmark) {
    scrollWordmark.style.transform = `translate3d(calc(${(-pageProgress * 18).toFixed(2)}vw), calc(${(-pageProgress * 6).toFixed(2)}vh), 0)`;
  }

  let activeIndex = 0;
  let activeDistance = Infinity;
  const viewportCenter = window.innerHeight * 0.48;

  sceneSections.forEach((section, index) => {
    const rect = section.getBoundingClientRect();
    const sectionCenter = rect.top + rect.height * 0.5;
    const distance = Math.abs(sectionCenter - viewportCenter);
    if (rect.bottom > 0 && rect.top < window.innerHeight && distance < activeDistance) {
      activeDistance = distance;
      activeIndex = index;
    }

    if (section.classList.contains('cinema-interlude')) {
      const sceneProgress = clamp((window.innerHeight - rect.top) / (window.innerHeight + rect.height));
      section.style.setProperty('--scene-progress', sceneProgress.toFixed(4));
    }
  });

  const aboutPortrait = document.querySelector('.about-portrait');
  if (aboutPortrait) {
    const rect = aboutPortrait.getBoundingClientRect();
    const visibility = clamp((window.innerHeight - rect.top) / (window.innerHeight + rect.height));
    const parallaxY = (visibility - 0.5) * -40;
    aboutPortrait.style.transform = `translateY(${parallaxY.toFixed(2)}px)`;
  }

  const heroVideo = document.querySelector('.hero-video');
  if (heroVideo) {
    const heroOffset = clamp(scrollTop / (window.innerHeight * 0.8));
    heroVideo.style.transform = `scale(${1 + heroOffset * 0.08}) translateY(${heroOffset * 30}px)`;
  }

  const active = sceneSections[activeIndex];
  if (hudIndex) hudIndex.textContent = String(activeIndex).padStart(2, '0');
  if (hudLabel && active) hudLabel.textContent = getSceneLabel(active);
  ticking = false;
};

const requestScrollMagic = () => {
  if (!ticking) {
    window.requestAnimationFrame(updateScrollMagic);
    ticking = true;
  }
};

window.addEventListener('resize', requestScrollMagic);
updateScrollMagic();

// Subtle editorial typography accent. Keep mobile work browsing direct and scannable.
const initGlitchText = () => {
  const headings = document.querySelectorAll('h1, h2, .section-kicker, .interlude-copy h3');

  headings.forEach(heading => {
    if (!heading.dataset.text) {
      heading.dataset.text = heading.textContent.trim();
    }
    heading.classList.add('glitch-text');
  });

  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        // Trigger glitch
        entry.target.classList.add('active');

        // Remove after animation
        setTimeout(() => {
          entry.target.classList.remove('active');
        }, 350);

        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.4 });

  headings.forEach(heading => observer.observe(heading));
};

document.addEventListener('DOMContentLoaded', () => {
  initGlitchText();
});

const detectInitialLanguage = () => {
  const saved = localStorage.getItem('kino-lang');
  if (saved && translations[saved]) return saved;

  const browserLanguages = navigator.languages?.length ? navigator.languages : [navigator.language || 'en'];
  const normalized = browserLanguages.map((lang) => lang.toLowerCase());

  if (normalized.some((lang) => lang.startsWith('de'))) return 'de';
  if (normalized.some((lang) => lang.startsWith('ru') || lang.startsWith('uk'))) return 'ru';
  return 'en';
};

setLanguage(detectInitialLanguage());
