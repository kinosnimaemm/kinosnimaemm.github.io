const heroTitle = document.querySelector('.hero-title');
if (heroTitle) {
  const titleLayers = heroTitle.querySelectorAll('span, em');
  let titleFrame = null;
  let titlePointerEvent = null;
  const updateTitleHoverPosition = (event) => {
    titlePointerEvent = event;
    if (titleFrame) return;

    titleFrame = requestAnimationFrame(() => {
      const pointer = titlePointerEvent;
      titleFrame = null;
      if (!pointer) return;

      titleLayers.forEach((layer) => {
        const layerRect = layer.getBoundingClientRect();
        layer.style.setProperty('--title-local-x', `${pointer.clientX - layerRect.left}px`);
        layer.style.setProperty('--title-local-y', `${pointer.clientY - layerRect.top}px`);
      });
    });
  };

  heroTitle.addEventListener('pointerenter', updateTitleHoverPosition);
  heroTitle.addEventListener('pointermove', updateTitleHoverPosition);
}

const setLanguage = (lang) => {
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.dataset.i18n;
    if (translations[lang][key]) {
      node.textContent = translations[lang][key];
      if (node.closest('.hero-title')) node.setAttribute('data-hover-text', translations[lang][key]);
    }
  });
  document.querySelectorAll('[data-lang]').forEach((button) => {
    button.classList.toggle('active', button.dataset.lang === lang);
  });
  localStorage.setItem('kino-lang', lang);
};

document.querySelectorAll('[data-lang]').forEach((button) => {
  button.addEventListener('click', () => setLanguage(button.dataset.lang));
});

const observer = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) entry.target.classList.add('visible');
  });
}, { threshold: 0.16 });

document.querySelectorAll('.reveal').forEach((node) => observer.observe(node));

const clipCards = document.querySelectorAll('.clip-card, .portrait-card');
clipCards.forEach((card) => {
  card.addEventListener('pointermove', (event) => {
    const rect = card.getBoundingClientRect();
    card.style.setProperty('--mx', `${((event.clientX - rect.left) / rect.width) * 100}%`);
    card.style.setProperty('--my', `${((event.clientY - rect.top) / rect.height) * 100}%`);
  });

  const video = card.querySelector('video');
  if (!video) return;
  card.setAttribute('tabindex', '0');
  video.pause();
  video.muted = true;
  video.playsInline = true;

  const play = () => {
    card.classList.add('is-playing');
    video.play().catch(() => card.classList.remove('is-playing'));
  };
  const pause = () => {
    video.pause();
    card.classList.remove('is-playing');
  };

  card.addEventListener('mouseenter', play);
  card.addEventListener('mouseleave', pause);
  card.addEventListener('focusin', play);
  card.addEventListener('focusout', pause);
  card.addEventListener('touchstart', () => {
    if (video.paused) play();
    else pause();
  }, { passive: true });
});

const playbackObserver = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (!entry.isIntersecting) {
      const video = entry.target.querySelector('video');
      if (video) video.pause();
      entry.target.classList.remove('is-playing');
    }
  });
}, { threshold: 0.08 });

clipCards.forEach((card) => playbackObserver.observe(card));


const ambientVideos = document.querySelectorAll('.ambient-video');
const ambientObserver = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    const video = entry.target;
    if (entry.isIntersecting) {
      video.play().catch(() => {});
    } else {
      video.pause();
    }
  });
}, { threshold: 0.18 });

ambientVideos.forEach((video) => {
  video.muted = true;
  video.playsInline = true;
  ambientObserver.observe(video);
});

const cursorLight = document.querySelector('.cursor-light');
if (cursorLight) {
  let cursorFrame = null;
  let cursorX = window.innerWidth / 2;
  let cursorY = window.innerHeight / 2;

  window.addEventListener('pointermove', (event) => {
    cursorX = event.clientX;
    cursorY = event.clientY;
    if (cursorFrame) return;

    cursorFrame = requestAnimationFrame(() => {
      cursorLight.style.transform = `translate3d(calc(${cursorX}px - 50%), calc(${cursorY}px - 50%), 0)`;
      cursorFrame = null;
    });
  });
}


const progressFill = document.querySelector('.scroll-progress span');
const hudIndex = document.querySelector('.hud-index');
const hudLabel = document.querySelector('.hud-label');
const sceneSections = [...document.querySelectorAll('.hero, .about-intro, .direction-panel, .cinema-interlude, .contact')];
let ticking = false;

const clamp = (value, min = 0, max = 1) => Math.min(max, Math.max(min, value));
const getSceneLabel = (section) => {
  if (section.classList.contains('hero')) return 'opening frame';
  if (section.classList.contains('contact')) return 'contact / booking';
  const heading = section.querySelector('h3, h2');
  return heading ? heading.textContent.trim() : 'portfolio scene';
};

const updateScrollMagic = () => {
  const scrollTop = window.scrollY || document.documentElement.scrollTop;
  const maxScroll = Math.max(1, document.documentElement.scrollHeight - window.innerHeight);
  const pageProgress = clamp(scrollTop / maxScroll);
  document.documentElement.style.setProperty('--page-progress', pageProgress.toFixed(4));
  if (progressFill) progressFill.style.transform = `scaleX(${pageProgress})`;

  let activeIndex = 0;
  let activeDistance = Infinity;
  const viewportCenter = window.innerHeight * 0.48;

  sceneSections.forEach((section, index) => {
    const rect = section.getBoundingClientRect();
    const sectionCenter = rect.top + rect.height * 0.5;
    const distance = Math.abs(sectionCenter - viewportCenter);
    if (rect.bottom > 0 && rect.top < window.innerHeight && distance < activeDistance) {
      activeDistance = distance;
      activeIndex = index;
    }

    if (section.classList.contains('cinema-interlude')) {
      const sceneProgress = clamp((window.innerHeight - rect.top) / (window.innerHeight + rect.height));
      section.style.setProperty('--scene-progress', sceneProgress.toFixed(4));
    }
  });

  const active = sceneSections[activeIndex];
  if (hudIndex) hudIndex.textContent = String(activeIndex).padStart(2, '0');
  if (hudLabel && active) hudLabel.textContent = getSceneLabel(active);
  ticking = false;
};

const requestScrollMagic = () => {
  if (!ticking) {
    window.requestAnimationFrame(updateScrollMagic);
    ticking = true;
  }
};

window.addEventListener('scroll', requestScrollMagic, { passive: true });
window.addEventListener('resize', requestScrollMagic);
updateScrollMagic();

const detectInitialLanguage = () => {
  const saved = localStorage.getItem('kino-lang');
  if (saved && translations[saved]) return saved;

  const browserLanguages = navigator.languages?.length ? navigator.languages : [navigator.language || 'en'];
  const normalized = browserLanguages.map((lang) => lang.toLowerCase());

  if (normalized.some((lang) => lang.startsWith('de'))) return 'de';
  if (normalized.some((lang) => lang.startsWith('ru') || lang.startsWith('uk'))) return 'ru';
  return 'en';
};

setLanguage(detectInitialLanguage());
