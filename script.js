const setLanguage = (lang) => {
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.dataset.i18n;
    if (translations[lang][key]) node.textContent = translations[lang][key];
  });
  document.querySelectorAll('[data-lang]').forEach((button) => {
    button.classList.toggle('active', button.dataset.lang === lang);
  });
  localStorage.setItem('kino-lang', lang);
};

document.querySelectorAll('[data-lang]').forEach((button) => {
  button.addEventListener('click', () => setLanguage(button.dataset.lang));
});

const observer = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) entry.target.classList.add('visible');
  });
}, { threshold: 0.16 });

document.querySelectorAll('.reveal').forEach((node) => observer.observe(node));

const clipCards = document.querySelectorAll('.clip-card, .portrait-card');
clipCards.forEach((card) => {
  const video = card.querySelector('video');
  if (!video) return;
  card.setAttribute('tabindex', '0');
  video.pause();
  video.muted = true;
  video.playsInline = true;

  const play = () => {
    card.classList.add('is-playing');
    video.play().catch(() => card.classList.remove('is-playing'));
  };
  const pause = () => {
    video.pause();
    card.classList.remove('is-playing');
  };

  card.addEventListener('mouseenter', play);
  card.addEventListener('mouseleave', pause);
  card.addEventListener('focusin', play);
  card.addEventListener('focusout', pause);
  card.addEventListener('touchstart', () => {
    if (video.paused) play();
    else pause();
  }, { passive: true });
});

const playbackObserver = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (!entry.isIntersecting) {
      const video = entry.target.querySelector('video');
      if (video) video.pause();
      entry.target.classList.remove('is-playing');
    }
  });
}, { threshold: 0.08 });

clipCards.forEach((card) => playbackObserver.observe(card));


const ambientVideos = document.querySelectorAll('.ambient-video');
const ambientObserver = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    const video = entry.target;
    if (entry.isIntersecting) {
      video.play().catch(() => {});
    } else {
      video.pause();
    }
  });
}, { threshold: 0.18 });

ambientVideos.forEach((video) => {
  video.muted = true;
  video.playsInline = true;
  ambientObserver.observe(video);
});

